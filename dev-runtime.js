export function createCommandRunner(spawn) {
  async function collect(stream, limit) {
    if (!stream) {
      return { text: '', truncated: false };
    }
    const reader = stream.getReader();
    let bytes = new Uint8Array(),
      truncated = false;
    try {
      for (;;) {
        // biome-ignore lint/performance/noAwaitInLoops: A readable stream yields one ordered chunk at a time and each retained tail depends on the prior bytes.
        const { value, done } = await reader.read();
        if (done) {
          break;
        }
        const joined = new Uint8Array(bytes.length + value.length);
        joined.set(bytes);
        joined.set(value, bytes.length);
        if (joined.length > limit) {
          truncated = true;
        }
        bytes = joined.slice(-limit);
      }
    } finally {
      reader.releaseLock();
    }
    return { text: new TextDecoder().decode(bytes).trim(), truncated };
  }
  return async (
    args,
    { cwd, timeoutMs = 3000, maxOutputBytes = 1024 * 1024 } = {}
  ) => {
    const proc = spawn(args, {
      cwd,
      stderr: 'pipe',
      stdin: 'ignore',
      stdout: 'pipe',
      timeout: timeoutMs,
    });
    const unknown = () =>
      Object.assign(
        new Error(
          'Command exit is unconfirmed; checkout ownership is retained'
        ),
        { code: 'OPERATION_UNKNOWN' }
      );
    const exited = Promise.resolve()
      .then(() => proc.exited)
      .then(
        (exitCode) => {
          if (!Number.isInteger(exitCode) || exitCode < 0) {
            throw unknown();
          }
          return exitCode;
        },
        () => {
          throw unknown();
        }
      );
    let values;
    try {
      values = await Promise.all([
        collect(proc.stdout, maxOutputBytes),
        collect(proc.stderr, 8192),
        exited,
      ]);
    } catch (error) {
      // A broken output stream is not evidence of exit. Conversely an unknown
      // exit must return promptly even if the child's output is still open.
      await exited;
      throw error;
    }
    const [stdout, stderr, code] = values;
    return {
      code,
      stderr: stderr.text,
      stderrTruncated: stderr.truncated,
      stdout: stdout.text,
      timedOut: !!proc.signalCode,
      truncated: stdout.truncated,
    };
  };
}

export function renderDockerCompose(
  spec,
  { wtDir, cacheDir, env = {}, envLocal = null }
) {
  if (!(spec.container && spec.limits?.cpus > 0 && spec.limits?.memMb > 0)) {
    throw new Error('An admitted container specification is required');
  }
  const environment = new Map([
    ['PORT', String(spec.port)],
    ['BUN_INSTALL_CACHE_DIR', '/bun-cache'],
  ]);
  for (const [key, value] of Object.entries(env)) {
    environment.set(key, value);
  }
  const volumes = [
    `${wtDir}:/workspace`,
    'node_modules:/workspace/node_modules',
    `${cacheDir}:/bun-cache`,
  ];
  if (envLocal) {
    volumes.push(`${envLocal.host}:${envLocal.container}`);
  }
  return `# Generated by setu; regenerated on container start.
name: ${spec.project}
services:
  dev:
    image: oven/bun:latest
    working_dir: /workspace
    command: sh -c "bun install && bun run dev"
    restart: on-failure:3
    mem_limit: "${spec.limits.memMb}m"
    cpus: "${spec.limits.cpus}"
    ports:
      - "${spec.port}:${spec.port}"
    environment:
${[...environment].map(([key, value]) => `      ${key}: ${JSON.stringify(String(value))}`).join('\n')}
    volumes:
${volumes.map((value) => `      - ${JSON.stringify(value)}`).join('\n')}
volumes:
  node_modules:
`;
}

export function createDevRuntime({
  spawn,
  signal,
  clock,
  prepareBare,
  prepareContainer,
  openLog,
  closeLog,
  containerState,
  composeDown,
  discover,
  startSidecars,
  sidecarStops,
  verifyHandle = async () => true,
}) {
  function processState(handle) {
    if (handle?.ownedGroup && handle.groupGone) {
      return 'dead';
    }
    if (!handle?.pid) {
      return 'dead';
    }
    try {
      signal(handle.ownedGroup ? -handle.pid : handle.pid, 0);
      return 'alive';
    } catch (error) {
      if (error.code === 'ESRCH') {
        if (handle.ownedGroup) {
          handle.groupGone = true;
        }
        return 'dead';
      }
      return 'unknown';
    }
  }
  async function discoverState(target) {
    // Sidecar entries are observed without a target; nothing to rediscover.
    return target ? (await discover(target)).state : 'unknown';
  }
  async function containerProcessState(handle, wrapper) {
    let state;
    try {
      state = await containerState(handle.container);
    } catch {
      state = 'unknown';
    }
    if (state === 'alive') {
      return 'alive';
    }
    return wrapper === 'dead' && state === 'dead' ? 'dead' : 'unknown';
  }
  async function observe(_target, handle) {
    if (
      !handle ||
      (!(handle.pid || handle.container) && handle.observedState === 'unknown')
    ) {
      return discoverState(_target);
    }
    const wrapper = processState(handle);
    if (
      wrapper === 'alive' &&
      !handle.ownedGroup &&
      !(await verifyHandle(handle))
    ) {
      return 'unknown';
    }
    if (wrapper === 'alive') {
      return 'alive';
    }
    if (!handle.container) {
      return wrapper;
    }
    return containerProcessState(handle, wrapper);
  }
  async function signalProcessPhase(handle, pid, name, timeout) {
    const state = processState(handle);
    if (state === 'dead') {
      return true;
    }
    if (state === 'unknown') {
      throw new Error(
        'Process ownership/liveness is unknown; Stop did not signal it.'
      );
    }
    if (!(handle.ownedGroup || (await verifyHandle(handle)))) {
      throw new Error(
        'Adopted process identity changed; Stop did not signal it.'
      );
    }
    try {
      signal(pid, name);
    } catch (error) {
      if (error.code !== 'ESRCH') {
        throw error;
      }
    }
    const deadline = clock.now() + timeout;
    // A terminated child can briefly be an unreaped zombie whose group probe
    // returns EPERM. Give the existing grace period a chance to establish
    // absence; an unknown result never authorizes the next signal.
    while (processState(handle) !== 'dead' && clock.now() < deadline) {
      // biome-ignore lint/performance/noAwaitInLoops: Each polling delay must observe the prior liveness result before another probe.
      await clock.sleep(50);
    }
    return false;
  }
  async function stopProcess(handle) {
    if (!handle?.pid) {
      return;
    }
    const pid = handle.ownedGroup ? -handle.pid : handle.pid;
    for (const [name, timeout] of [
      ['SIGTERM', 5000],
      ['SIGKILL', 2000],
    ]) {
      // biome-ignore lint/performance/noAwaitInLoops: SIGKILL is permitted only after the prior signal phase's current ownership proof.
      if (await signalProcessPhase(handle, pid, name, timeout)) {
        return;
      }
    }
    if (processState(handle) !== 'dead') {
      throw new Error(
        'Dev process did not confirm exit; ownership is retained. Retry Stop.'
      );
    }
  }
  async function launch(
    target,
    spec,
    registerHandle,
    { sidecars = true } = {}
  ) {
    const prepared = spec.container
      ? await prepareContainer(target, spec)
      : await prepareBare(target, spec);
    const fd = await openLog(target);
    let handle;
    try {
      const proc = spawn(
        spec.container
          ? [
              'docker',
              'compose',
              '-p',
              spec.project,
              '-f',
              prepared,
              'up',
              '--build',
              '--no-color',
            ]
          : ['bun', 'dev'],
        {
          cwd: target.wtDir,
          ...(spec.container ? {} : { env: prepared }),
          detached: true,
          stderr: fd,
          stdout: fd,
        }
      );
      handle = {
        exited: proc.exited,
        native: proc,
        ownedGroup: true,
        pid: proc.pid,
        ...(spec.container
          ? { composePath: prepared, container: spec.project }
          : {}),
      };
      // Ownership is published before close/sidecar work can fail.
      registerHandle(handle);
    } finally {
      await closeLog(fd);
    }
    const skippedSidecars = sidecars ? await startSidecars(target) : [];
    return { skippedSidecars };
  }
  async function stop(target, suppliedHandle, { sidecars = true } = {}) {
    let handle = suppliedHandle;
    if (
      !handle ||
      (!(handle.pid || handle.container) && handle.observedState === 'unknown')
    ) {
      const found = await discover(target);
      if (
        !['alive', 'dead'].includes(found.state) ||
        (found.state === 'alive' && !found.handle)
      ) {
        throw new Error(
          `Setu could not identify the process on port ${target.port}. If nothing is running there, press Stop again. Otherwise stop it from Active ports, then press Stop.`
        );
      }
      handle = found.handle ?? null;
    }
    const results = await Promise.allSettled([
      (async () => {
        await stopProcess(handle);
        if (handle?.container) {
          await composeDown(
            handle.container,
            handle.composePath ?? `${target.wtDir}/docker-compose.setu.yml`
          );
        }
        if (handle && (await observe(target, handle)) !== 'dead') {
          throw new Error(
            'Runtime exit is not confirmed; ownership is retained.'
          );
        }
      })(),
      ...(sidecars
        ? sidecarStops.map((stopSidecar) =>
            Promise.resolve().then(() => stopSidecar(target))
          )
        : []),
    ]);
    if (results[0].status === 'rejected') {
      throw results[0].reason;
    }
    const warnings = results
      .slice(1)
      .filter((result) => result.status === 'rejected')
      .map((result) => String(result.reason?.message ?? result.reason));
    return { warnings };
  }
  return Object.freeze({ launch, observe, stop, stopProcess });
}
