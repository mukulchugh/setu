//! Recipes: what a kind of project needs besides its web server, as data.
//!
//! A recipe is a TOML file (`recipes/*.toml` in the binary, plus `<config dir>/recipes/*.toml`
//! of your own; a user recipe replaces a shipped one with the same name). It says how to detect
//! itself in a checkout and which ports, env and procs it adds. A project config names the recipes
//! it uses (`recipes = ["name", ...]`) and `config.rs` merges them in when it loads, with every key
//! written in the project winning. `setu import-v1` writes that line from detection.
//! Setu's code knows no tool by name: everything about a tool lives in its recipe.
//!
//! `{port.X}`, `{url}`, `{run}` and `{worktree}` stay in the merged values and are resolved when a
//! run starts. Four more are filled in once per config load, from the main worktree: `{dir}` (where
//! the recipe's detect rule matched, relative to the worktree, empty for the root), `{app_dir}`
//! (`apps/<project>` when that folder exists, else `.`), `{pm}` (the package manager, from the
//! lockfile) and `{pm_exec}` (its one-off runner, such as `bunx`). A literal brace in a command is
//! written `{{` or `}}`, as everywhere in project configs.

use crate::{paths, presets};
use anyhow::{bail, Context, Result};
use serde::Deserialize;
use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};

#[derive(Deserialize, Debug, Clone, PartialEq, Default)]
#[serde(deny_unknown_fields)]
struct Rule {
    /// A path or glob relative to the worktree root (`tool.config.*`, `apps/*/x.json`).
    file: Option<String>,
    /// A dependency name in the package.json of the root or of an `apps/*` folder.
    dependency: Option<String>,
    /// A directory path or glob relative to the worktree root.
    dir: Option<String>,
}

#[derive(Deserialize, Debug, Clone, PartialEq, Default)]
#[serde(deny_unknown_fields)]
struct Detect {
    #[serde(default)]
    any_of: Vec<Rule>,
}

#[derive(Deserialize, Debug, Clone, PartialEq)]
#[serde(deny_unknown_fields)]
pub struct RecipeProc {
    pub run: String,
    pub port: Option<String>,
    pub cwd: Option<String>,
}

#[derive(Deserialize, Debug, Clone, PartialEq)]
#[serde(deny_unknown_fields)]
pub struct Recipe {
    pub name: String,
    #[serde(default)]
    pub description: String,
    /// Names of the old `setu x <helper>` commands this recipe took over (for `setu doctor`).
    #[serde(default)]
    pub replaces: Vec<String>,
    #[serde(default)]
    detect: Detect,
    /// Port names to lease.
    #[serde(default)]
    pub ports: BTreeMap<String, toml::Value>,
    #[serde(default)]
    pub env: BTreeMap<String, String>,
    #[serde(default)]
    pub procs: BTreeMap<String, RecipeProc>,
}

#[derive(Debug, Clone, PartialEq)]
pub enum Origin {
    Shipped,
    User(PathBuf),
}

/// A recipe with where it came from and its source text (what `setu recipes show` prints).
#[derive(Debug, Clone, PartialEq)]
pub struct Loaded {
    pub recipe: Recipe,
    pub origin: Origin,
    /// A user recipe with the same name as a shipped one replaced it.
    pub overrides_shipped: bool,
    pub text: String,
}

// Generated by build.rs from recipes/*.toml: (file stem, text).
include!(concat!(env!("OUT_DIR"), "/shipped_recipes.rs"));

pub fn parse(text: &str, what: &str) -> Result<Recipe> {
    let r: Recipe = toml::from_str(text).with_context(|| format!("recipe {what}"))?;
    if r.name.is_empty() || !r.name.chars().all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_') {
        bail!("recipe {what}: name {:?} must be letters, digits, '-' or '_'", r.name);
    }
    for rule in &r.detect.any_of {
        if [&rule.file, &rule.dependency, &rule.dir].iter().filter(|x| x.is_some()).count() != 1 {
            bail!("recipe {what}: each detect rule needs exactly one of file, dependency, dir");
        }
    }
    if r.detect.any_of.is_empty() {
        bail!("recipe {what}: [detect] any_of needs at least one rule");
    }
    for (n, p) in &r.procs {
        if let Some(port) = &p.port {
            if !r.ports.contains_key(port) && port != "web" {
                bail!("recipe {what}: proc {n:?} uses port {port:?} which is not in [ports]");
            }
        }
    }
    Ok(r)
}

pub fn user_dir() -> PathBuf {
    paths::config_dir().join("recipes")
}

/// The shipped recipes, then the ones in `user` (a directory), user files replacing shipped ones by name.
pub fn load_from(user: Option<&Path>) -> Result<Vec<Loaded>> {
    let mut out: Vec<Loaded> = SHIPPED
        .iter()
        .map(|(n, t)| Ok(Loaded { recipe: parse(t, n)?, origin: Origin::Shipped, overrides_shipped: false, text: t.to_string() }))
        .collect::<Result<_>>()?;
    let Some(dir) = user else { return Ok(out) };
    let Ok(rd) = std::fs::read_dir(dir) else { return Ok(out) };
    let mut files: Vec<PathBuf> = rd.filter_map(Result::ok).map(|e| e.path()).filter(|p| p.extension().is_some_and(|e| e == "toml") && p.is_file()).collect();
    files.sort();
    for f in files {
        let text = std::fs::read_to_string(&f).with_context(|| format!("reading {}", f.display()))?;
        let recipe = parse(&text, &f.display().to_string())?;
        match out.iter().position(|l| l.recipe.name == recipe.name) {
            Some(i) => {
                let shipped = out[i].origin == Origin::Shipped || out[i].overrides_shipped;
                out[i] = Loaded { recipe, origin: Origin::User(f), overrides_shipped: shipped, text };
            }
            None => out.push(Loaded { recipe, origin: Origin::User(f), overrides_shipped: false, text }),
        }
    }
    Ok(out)
}

pub fn load() -> Result<Vec<Loaded>> {
    load_from(Some(&user_dir()))
}

/// A recipe that matched a checkout, with the values for its generation-time variables.
#[derive(Debug, Clone, PartialEq)]
pub struct Matched {
    pub recipe: Recipe,
    pub dir: String,
    pub app_dir: String,
}

/// Directories to look in for package.json: the root, `apps/<app>`, then the other apps.
fn package_dirs(root: &Path, app: &str) -> Vec<String> {
    let mut dirs: Vec<String> = vec![String::new(), format!("apps/{app}")];
    if let Ok(rd) = std::fs::read_dir(root.join("apps")) {
        let mut more: Vec<String> = rd.filter_map(Result::ok).filter(|e| e.path().is_dir()).filter_map(|e| e.file_name().to_str().map(|n| format!("apps/{n}"))).collect();
        more.sort();
        dirs.extend(more.into_iter().take(20));
    }
    let mut seen = BTreeSet::new();
    dirs.retain(|d| seen.insert(d.clone()));
    dirs
}

fn has_dependency(dir: &Path, name: &str) -> bool {
    let Ok(text) = std::fs::read_to_string(dir.join("package.json")) else { return false };
    let Ok(v) = serde_json::from_str::<serde_json::Value>(&text) else { return false };
    ["dependencies", "devDependencies"].iter().any(|k| v.get(k).and_then(|o| o.get(name)).is_some())
}

fn rel_parent(root: &Path, p: &Path) -> String {
    p.parent().and_then(|d| d.strip_prefix(root).ok()).map(|d| d.to_string_lossy().into_owned()).unwrap_or_default()
}

/// Where `rule` matches under `root`: the directory (relative to the root, "" for the root) of the first hit.
fn rule_dir(root: &Path, app: &str, rule: &Rule) -> Option<String> {
    if let Some(f) = &rule.file {
        return presets::expand_paths(root, f).iter().find(|p| p.is_file()).map(|p| rel_parent(root, p));
    }
    if let Some(d) = &rule.dir {
        return presets::expand_paths(root, d).iter().find(|p| p.is_dir()).map(|p| rel_parent(root, p));
    }
    let dep = rule.dependency.as_ref()?;
    package_dirs(root, app).into_iter().find(|rel| has_dependency(&root.join(rel), dep))
}

/// `apps/<app>` when that folder exists under `root`, else `.`.
pub fn app_dir(root: &Path, app: &str) -> String {
    if root.join("apps").join(app).is_dir() {
        format!("apps/{app}")
    } else {
        ".".to_string()
    }
}

/// The package manager of the checkout at `root`, from its lockfile (`npm` when there is none).
pub fn package_manager(root: &Path) -> &'static str {
    let has = |f: &str| root.join(f).exists();
    if has("bun.lock") || has("bun.lockb") {
        "bun"
    } else if has("pnpm-lock.yaml") {
        "pnpm"
    } else if has("yarn.lock") {
        "yarn"
    } else {
        "npm"
    }
}

/// Where the first of the recipe's detect rules that matches under `root` found it (relative, "" for the root).
fn detect_dir(root: &Path, app: &str, l: &Loaded) -> Option<String> {
    l.recipe.detect.any_of.iter().find_map(|r| rule_dir(root, app, r))
}

/// The recipes that apply to the checkout at `root`. `app` is the project's name (its `apps/<app>` folder).
pub fn detect(root: &Path, app: &str, recipes: &[Loaded]) -> Vec<Matched> {
    let app_dir = app_dir(root, app);
    recipes
        .iter()
        .filter_map(|l| Some(Matched { recipe: l.recipe.clone(), dir: detect_dir(root, app, l)?, app_dir: app_dir.clone() }))
        .collect()
}

/// The named recipes with their generation-time variables filled in from the checkout at `root`
/// (which may not exist: `{dir}` is then empty, `{app_dir}` is `.` and `{pm}` is `npm`).
/// An unknown name is an error that names `file` and lists the available recipes.
pub fn resolve(names: &[String], file: &Path, root: &Path, app: &str, user: Option<&Path>) -> Result<Vec<Recipe>> {
    let all = load_from(user)?;
    let pm = package_manager(root);
    let app_dir = app_dir(root, app);
    let mut out: Vec<Recipe> = Vec::new();
    for n in names {
        let Some(l) = all.iter().find(|l| l.recipe.name == *n) else {
            let avail: Vec<&str> = all.iter().map(|l| l.recipe.name.as_str()).collect();
            bail!("{}: unknown recipe {n:?}; available recipes: {}", file.display(), avail.join(", "));
        };
        if out.iter().any(|r| r.name == *n) {
            continue;
        }
        let m = Matched { recipe: l.recipe.clone(), dir: detect_dir(root, app, l).unwrap_or_default(), app_dir: app_dir.clone() };
        let mut r = l.recipe.clone();
        for v in r.env.values_mut() {
            *v = fill(v, &m, pm);
        }
        for p in r.procs.values_mut() {
            p.run = fill(&p.run, &m, pm);
            p.cwd = p.cwd.as_deref().map(|c| fill(c, &m, pm));
        }
        out.push(r);
    }
    Ok(out)
}

/// Fill in `{dir}`, `{app_dir}`, `{pm}` and `{pm_exec}`; every other `{...}` is left for run time.
pub fn fill(template: &str, m: &Matched, pm: &str) -> String {
    let pm = if pm.is_empty() { "npm" } else { pm };
    let exec = match pm {
        "bun" => "bunx",
        "pnpm" => "pnpm exec",
        "yarn" => "yarn",
        _ => "npx",
    };
    template.replace("{dir}", &m.dir).replace("{app_dir}", &m.app_dir).replace("{pm_exec}", exec).replace("{pm}", pm)
}

/// The name of the recipe that replaced the old `setu x <helper>` command.
pub fn recipe_for_helper(helper: &str) -> Option<String> {
    let all = load().ok()?;
    all.iter().find(|l| l.recipe.replaces.iter().any(|r| r == helper)).map(|l| l.recipe.name.clone())
}

/// `setu recipes [ls|show <name>]`
pub fn main(args: &[String]) -> Result<()> {
    let all = load()?;
    match args.first().map(String::as_str) {
        None | Some("ls") => {
            let w = all.iter().map(|l| l.recipe.name.len()).max().unwrap_or(0);
            for l in &all {
                let from = match (&l.origin, l.overrides_shipped) {
                    (Origin::Shipped, _) => "shipped".to_string(),
                    (Origin::User(p), true) => format!("yours, replaces the shipped one ({})", p.display()),
                    (Origin::User(p), false) => format!("yours ({})", p.display()),
                };
                println!("{:<w$}  {from}\n{:<w$}  {}", l.recipe.name, "", l.recipe.description);
            }
            println!("\nYour own recipes go in {}", user_dir().display());
            Ok(())
        }
        Some("show") => {
            let name = args.get(1).map(String::as_str).unwrap_or_default();
            match all.iter().find(|l| l.recipe.name == name) {
                Some(l) => {
                    print!("{}", l.text);
                    Ok(())
                }
                None => bail!("no recipe named {name:?}; `setu recipes ls` lists them"),
            }
        }
        Some(other) => bail!("unknown argument {other:?}; usage: setu recipes [ls|show <name>]"),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tmp(tag: &str) -> PathBuf {
        let d = std::env::temp_dir().join(format!("setu-recipes-{tag}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&d);
        std::fs::create_dir_all(&d).unwrap();
        d
    }
    fn write_all(root: &Path, files: &[(&str, &str)]) {
        for (f, c) in files {
            let p = root.join(f);
            std::fs::create_dir_all(p.parent().unwrap()).unwrap();
            std::fs::write(p, c).unwrap();
        }
    }
    fn names(root: &Path) -> Vec<String> {
        detect(root, "app", &load_from(None).unwrap()).into_iter().map(|m| m.recipe.name).collect()
    }

    #[test]
    fn shipped_recipes_parse() {
        let all = load_from(None).unwrap();
        let got: Vec<&str> = all.iter().map(|l| l.recipe.name.as_str()).collect();
        assert_eq!(got, ["convex", "inngest", "next-env", "nx", "trigger", "workos-authkit"]);
        for (n, _) in SHIPPED {
            assert!(all.iter().any(|l| l.recipe.name == *n), "{n} must be named after its file");
        }
        let r = parse(
            "name = \"x\"\ndescription = \"d\"\n[detect]\nany_of = [{ file = \"a.*\" }, { dependency = \"d\" }, { dir = \"apps/*/x\" }]\n[ports]\nq = {}\n[env]\nK = \"{url}\"\n[procs.p]\nrun = \"go {port.q}\"\nport = \"q\"\ncwd = \"{dir}\"\n",
            "t",
        )
        .unwrap();
        assert_eq!(r.procs["p"].port.as_deref(), Some("q"));
        assert!(parse("name = \"x\"\n[detect]\nany_of = [{ file = \"a\", dir = \"b\" }]\n", "t").is_err(), "two keys in one rule");
        assert!(parse("name = \"x\"\n", "t").is_err(), "no detect rules");
        assert!(parse("name = \"x\"\nnope = 1\n[detect]\nany_of = [{ file = \"a\" }]\n", "t").is_err(), "unknown key");
    }

    #[test]
    fn each_shipped_recipe_detects_its_own_stack() {
        let d = tmp("detect");
        assert!(names(&d).is_empty());
        write_all(&d, &[("package.json", r#"{"dependencies":{"react":"1"}}"#)]);
        assert_eq!(names(&d), ["next-env"]);
        write_all(&d, &[("nx.json", "{}")]);
        assert_eq!(names(&d), ["next-env", "nx"]);
        write_all(&d, &[("apps/app/package.json", r#"{"devDependencies":{"inngest":"3","@workos-inc/authkit-nextjs":"2"}}"#)]);
        assert_eq!(names(&d), ["inngest", "next-env", "nx", "workos-authkit"]);
        write_all(&d, &[("apps/other/trigger.config.ts", "")]);
        let m = detect(&d, "app", &load_from(None).unwrap());
        assert_eq!(m.iter().find(|m| m.recipe.name == "trigger").unwrap().dir, "apps/other");
        write_all(&d, &[("trigger.config.mjs", "")]);
        let m = detect(&d, "app", &load_from(None).unwrap());
        assert_eq!(m.iter().find(|m| m.recipe.name == "trigger").unwrap().dir, "", "a config at the root wins");
        assert_eq!(m.iter().find(|m| m.recipe.name == "trigger").unwrap().app_dir, "apps/app");
        // the dependency alone is enough
        let e = tmp("detect-dep");
        write_all(&e, &[("apps/web/package.json", r#"{"dependencies":{"@trigger.dev/sdk":"^4"}}"#)]);
        assert_eq!(detect(&e, "x", &load_from(None).unwrap())[0].dir, "apps/web");
        assert_eq!(detect(&e, "x", &load_from(None).unwrap())[0].app_dir, ".");
        // nx by its dependency, convex by its dependency and by its folder
        let f = tmp("detect-nx");
        write_all(&f, &[("package.json", r#"{"devDependencies":{"nx":"20","convex":"1"}}"#)]);
        assert_eq!(names(&f), ["convex", "next-env", "nx"]);
        let g = tmp("detect-convex-dir");
        write_all(&g, &[("apps/web/convex/schema.ts", "")]);
        let m = detect(&g, "x", &load_from(None).unwrap());
        assert_eq!((m[0].recipe.name.as_str(), m[0].dir.as_str()), ("convex", "apps/web"));
    }

    #[test]
    fn fill_resolves_only_generation_time_variables() {
        let m = Matched { recipe: load_from(None).unwrap().remove(0).recipe, dir: "apps/web".into(), app_dir: ".".into() };
        assert_eq!(fill("{pm_exec} x {dir} {app_dir} {pm} {port.web} {url} {run}", &m, "pnpm"), "pnpm exec x apps/web . pnpm {port.web} {url} {run}");
        for (pm, want) in [("bun", "bunx"), ("yarn", "yarn"), ("npm", "npx"), ("", "npx")] {
            assert_eq!(fill("{pm_exec}", &m, pm), want);
        }
    }

    #[test]
    fn a_user_recipe_replaces_a_shipped_one_by_name_and_can_add_new_ones() {
        let u = tmp("user");
        write_all(
            &u,
            &[
                ("mine.toml", "name = \"nx\"\ndescription = \"mine\"\n[detect]\nany_of = [{ file = \"nx.json\" }]\n[env]\nNX_DAEMON = \"true\"\n"),
                ("extra.toml", "name = \"extra\"\n[detect]\nany_of = [{ file = \"extra.txt\" }]\n[env]\nE = \"1\"\n"),
                ("notes.txt", "not a recipe"),
            ],
        );
        let all = load_from(Some(&u)).unwrap();
        assert_eq!(all.len(), 7);
        let nx = all.iter().find(|l| l.recipe.name == "nx").unwrap();
        assert_eq!(nx.recipe.env["NX_DAEMON"], "true");
        assert!(nx.overrides_shipped && matches!(nx.origin, Origin::User(_)));
        assert!(!all.iter().find(|l| l.recipe.name == "extra").unwrap().overrides_shipped);
        assert_eq!(all.iter().filter(|l| l.recipe.name == "nx").count(), 1);
        let d = tmp("user-wt");
        write_all(&d, &[("nx.json", "{}"), ("extra.txt", "")]);
        let got = detect(&d, "a", &all);
        assert!(got.iter().any(|m| m.recipe.name == "extra") && got.iter().any(|m| m.recipe.env.get("NX_DAEMON").map(String::as_str) == Some("true")));
        // a broken user recipe is an error that names the file, not a silent skip
        write_all(&u, &[("bad.toml", "name = \"bad\"\n")]);
        assert!(load_from(Some(&u)).unwrap_err().to_string().contains("bad.toml"));
    }

    #[test]
    fn the_source_names_no_third_party_tool() {
        let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("src");
        let mut seen = 0;
        for e in std::fs::read_dir(dir).unwrap().flatten() {
            let text = std::fs::read_to_string(e.path()).unwrap();
            // Tests may use any fixture; only the code above the test module counts.
            let code = text.split("#[cfg(test)]").next().unwrap().to_lowercase();
            for word in ["trigger", "inngest", "convex", "workos"] {
                assert!(!code.contains(word), "{} names {word}: move it into a recipe", e.path().display());
            }
            seen += 1;
        }
        assert!(seen > 20);
    }
}
