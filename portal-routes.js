export function portalApiRoute(pathname, method) {
  return PORTAL_API_ROUTES.find(
    (route) =>
      route.methods.includes(method) &&
      (route.path === pathname ||
        (route.path.endsWith('/:serverId') &&
          pathname.startsWith(route.path.slice(0, -':serverId'.length))))
  );
}
